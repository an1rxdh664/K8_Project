#!/usr/bin/env bash
# gitops-register.sh
# Registers an onboarded service as an ArgoCD Application.
# Reads all values from the .onboard.conf — nothing hardcoded.
# The generated Application manifest is saved to manifests/<service>/06-argocd-app.yaml
#
# Usage:
#   ./gitops-register.sh <path/to/service.onboard.conf>
#   ./gitops-register.sh --deregister <service-name>

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
die()     { echo -e "${RED}[ERROR]${NC} $*" >&2; exit 1; }
header()  { echo -e "\n${BOLD}${CYAN}$*${NC}"; }

ARGOCD_NAMESPACE="${ARGOCD_NAMESPACE:-argocd}"
APPS_NAMESPACE="${APPS_NAMESPACE:-apps}"
# Path within the repo where manifests live (default: manifests/<service-name>/)
# ArgoCD will sync everything in this path.
MANIFEST_PATH_IN_REPO="${MANIFEST_PATH_IN_REPO:-}"  # auto-derived if empty
SYNC_POLICY="${SYNC_POLICY:-automated}"   # automated | manual
CONF_FILE=""
DEREGISTER_NAME=""

usage() {
  cat <<EOF
${BOLD}gitops-register.sh${NC} — Register a service with ArgoCD

${BOLD}Usage:${NC}
  ./gitops-register.sh <service.onboard.conf>
  ./gitops-register.sh --deregister <service-name>

${BOLD}Environment variables:${NC}
  ARGOCD_NAMESPACE      ArgoCD namespace (default: argocd)
  APPS_NAMESPACE        Target namespace (default: apps)
  MANIFEST_PATH_IN_REPO Path in repo to sync from (default: manifests/<service>/)
  SYNC_POLICY           automated | manual (default: automated)
EOF
  exit 0
}

load_config() {
  [[ -f "$CONF_FILE" ]] || die "Config not found: $CONF_FILE"
  # shellcheck source=/dev/null
  source "$CONF_FILE"
  for var in SERVICE_NAME REPO_URL BRANCH; do
    [[ -n "${!var:-}" ]] || die "Config missing: $var"
  done
  # Derive manifest path in repo if not set
  if [[ -z "$MANIFEST_PATH_IN_REPO" ]]; then
    MANIFEST_PATH_IN_REPO="manifests/${SERVICE_NAME}"
  fi
}

check_argocd() {
  kubectl get namespace "$ARGOCD_NAMESPACE" &>/dev/null \
    || die "ArgoCD namespace '$ARGOCD_NAMESPACE' not found. Run ./setup-argocd.sh first."
  kubectl get deployment argocd-server -n "$ARGOCD_NAMESPACE" &>/dev/null \
    || die "ArgoCD server not found. Run ./setup-argocd.sh first."
}

gen_argocd_application() {
  local out_dir
  out_dir="$(dirname "$CONF_FILE")/${SERVICE_NAME}"
  mkdir -p "$out_dir"

  local sync_policy_block=""
  if [[ "$SYNC_POLICY" == "automated" ]]; then
    sync_policy_block="  automated:
      prune: true
      selfHeal: true"
  fi

  cat > "$out_dir/06-argocd-app.yaml" <<EOF
# 06-argocd-app.yaml — ArgoCD Application for $SERVICE_NAME
# Generated by gitops-register.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Apply with: kubectl apply -f $out_dir/06-argocd-app.yaml
apiVersion: argoproj.io/v1alpha1
kind: Application
metadata:
  name: ${SERVICE_NAME}
  namespace: ${ARGOCD_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    app.kubernetes.io/managed-by: platform
  # Cascade delete: removing the Application also removes cluster resources
  finalizers:
    - resources-finalizer.argocd.argoproj.io
spec:
  project: default
  source:
    repoURL: ${REPO_URL}
    targetRevision: ${BRANCH}
    path: ${MANIFEST_PATH_IN_REPO}
    # If using kustomize (kustomization.yaml exists in path):
    kustomize: {}
  destination:
    server: https://kubernetes.default.svc
    namespace: ${APPS_NAMESPACE}
  syncPolicy:
${sync_policy_block:-    {}}
    syncOptions:
      - CreateNamespace=false
      - PrunePropagationPolicy=foreground
      - ApplyOutOfSyncOnly=true
  # Health check overrides if needed (extend per service requirements)
  ignoreDifferences:
    - group: apps
      kind: Deployment
      jsonPointers:
        - /spec/replicas   # Allow KEDA to manage replicas without ArgoCD reverting
EOF

  info "Generated: $out_dir/06-argocd-app.yaml"
  echo "$out_dir/06-argocd-app.yaml"
}

apply_application() {
  local manifest_file="$1"
  info "Applying ArgoCD Application for $SERVICE_NAME"
  kubectl apply -f "$manifest_file"

  # Wait for app to appear
  local retries=10
  while [[ $retries -gt 0 ]]; do
    if kubectl get application "$SERVICE_NAME" -n "$ARGOCD_NAMESPACE" &>/dev/null; then
      break
    fi
    sleep 2
    retries=$(( retries - 1 ))
  done

  success "ArgoCD Application '$SERVICE_NAME' registered"
}

deregister() {
  local name="$1"
  info "Deregistering ArgoCD Application: $name"
  kubectl delete application "$name" -n "$ARGOCD_NAMESPACE" --ignore-not-found
  success "Deregistered $name"
  echo ""
  echo "  Cluster resources may have been pruned (cascade delete)."
  echo "  To keep resources: remove the finalizer before deleting."
}

print_summary() {
  header "GitOps registration complete — $SERVICE_NAME"
  echo ""
  echo "  App name  : $SERVICE_NAME"
  echo "  Repo      : $REPO_URL @ $BRANCH"
  echo "  Path      : $MANIFEST_PATH_IN_REPO"
  echo "  Namespace : $APPS_NAMESPACE"
  echo "  Sync      : $SYNC_POLICY"
  echo ""
  echo "  Check sync status:"
  echo "    kubectl get application $SERVICE_NAME -n $ARGOCD_NAMESPACE"
  echo "    kubectl describe application $SERVICE_NAME -n $ARGOCD_NAMESPACE"
  echo ""
  echo "  Force sync:"
  echo "    kubectl patch application $SERVICE_NAME -n $ARGOCD_NAMESPACE \\"
  echo "      --type merge -p '{\"operation\":{\"sync\":{}}}'"
  echo ""
  echo "  UI: kubectl port-forward svc/argocd-server -n $ARGOCD_NAMESPACE 8080:80"
}

main() {
  case "${1:-}" in
    --help|-h) usage ;;
    --deregister)
      [[ -n "${2:-}" ]] || die "--deregister requires a service name"
      DEREGISTER_NAME="$2"
      check_argocd
      deregister "$DEREGISTER_NAME"
      exit 0
      ;;
    "")
      die "Usage: ./gitops-register.sh <service.onboard.conf>  |  --help"
      ;;
    *)
      CONF_FILE="$1"
      ;;
  esac

  header "Kubernetes Platform — GitOps Registration"
  load_config
  check_argocd
  local manifest
  manifest=$(gen_argocd_application)
  apply_application "$manifest"
  print_summary
}

main "$@"
