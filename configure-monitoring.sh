#!/usr/bin/env bash
# configure-monitoring.sh
# Generates a Prometheus ServiceMonitor for an onboarded service.
# All values come from the .onboard.conf — nothing hardcoded.
# Also generates a per-service Grafana dashboard ConfigMap.
#
# Usage:
#   ./configure-monitoring.sh <service.onboard.conf>
#   ./configure-monitoring.sh <service.onboard.conf> --metrics-path /metrics --metrics-port 9090

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
die()     { echo -e "${RED}[ERROR]${NC} $*" >&2; exit 1; }
header()  { echo -e "\n${BOLD}${CYAN}$*${NC}"; }

CONF_FILE=""
METRICS_PATH="${METRICS_PATH:-/metrics}"
METRICS_PORT="${METRICS_PORT:-}"          # defaults to service app port
SCRAPE_INTERVAL="${SCRAPE_INTERVAL:-15s}"
APPLY="${APPLY:-true}"
APPS_NAMESPACE="${APPS_NAMESPACE:-apps}"
OBS_NAMESPACE="${OBS_NAMESPACE:-observability}"

parse_args() {
  [[ $# -eq 0 ]] && die "Usage: ./configure-monitoring.sh <service.onboard.conf>"
  CONF_FILE="$1"; shift
  while [[ $# -gt 0 ]]; do
    case "$1" in
      --metrics-path)   METRICS_PATH="$2";   shift 2 ;;
      --metrics-port)   METRICS_PORT="$2";   shift 2 ;;
      --interval)       SCRAPE_INTERVAL="$2"; shift 2 ;;
      --no-apply)       APPLY="false";        shift ;;
      --help|-h)
        echo "Usage: ./configure-monitoring.sh <service.onboard.conf> [--metrics-path /metrics] [--metrics-port 9090] [--interval 15s]"
        exit 0 ;;
      *) die "Unknown option: $1" ;;
    esac
  done
}

load_config() {
  [[ -f "$CONF_FILE" ]] || die "Config not found: $CONF_FILE"
  # shellcheck source=/dev/null
  source "$CONF_FILE"
  for var in SERVICE_NAME PORT APPS_NAMESPACE; do
    [[ -n "${!var:-}" ]] || die "Config missing: $var"
  done
  APPS_NAMESPACE="${APPS_NAMESPACE}"
  # Default metrics port to service app port
  [[ -z "$METRICS_PORT" ]] && METRICS_PORT="$PORT"
}

# ── 08-servicemonitor.yaml ────────────────────────────────────────────────────
gen_servicemonitor() {
  local out_dir
  out_dir="$(dirname "$CONF_FILE")/${SERVICE_NAME}"
  mkdir -p "$out_dir"

  cat > "$out_dir/08-servicemonitor.yaml" <<EOF
# 08-servicemonitor.yaml — Prometheus ServiceMonitor for $SERVICE_NAME
# Generated by configure-monitoring.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: monitoring.coreos.com/v1
kind: ServiceMonitor
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    # This label is what Prometheus Operator uses to discover ServiceMonitors
    release: prometheus
spec:
  selector:
    matchLabels:
      app.kubernetes.io/name: ${SERVICE_NAME}
  namespaceSelector:
    matchNames:
      - ${APPS_NAMESPACE}
  endpoints:
    - port: http
      path: ${METRICS_PATH}
      interval: ${SCRAPE_INTERVAL}
      scheme: http
      relabelings:
        - sourceLabels: [__meta_kubernetes_pod_name]
          targetLabel: pod
        - sourceLabels: [__meta_kubernetes_namespace]
          targetLabel: namespace
        - targetLabel: service
          replacement: ${SERVICE_NAME}
EOF

  info "Generated: $out_dir/08-servicemonitor.yaml"
  echo "$out_dir/08-servicemonitor.yaml"
}

# ── Per-service Grafana dashboard ConfigMap ───────────────────────────────────
gen_service_dashboard() {
  local out_dir
  out_dir="$(dirname "$CONF_FILE")/${SERVICE_NAME}"

  # Grafana dashboard JSON — covers request rate, error rate, latency, pod count
  # Uses template variables so it works for any service name
  cat > "$out_dir/09-grafana-dashboard.yaml" <<YAML
# 09-grafana-dashboard.yaml — Grafana dashboard ConfigMap for $SERVICE_NAME
# Generated by configure-monitoring.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# Grafana sidecar picks this up automatically via the grafana_dashboard label.
apiVersion: v1
kind: ConfigMap
metadata:
  name: ${SERVICE_NAME}-dashboard
  namespace: ${OBS_NAMESPACE}
  labels:
    grafana_dashboard: "1"
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
data:
  ${SERVICE_NAME}-dashboard.json: |
    {
      "title": "${SERVICE_NAME} — Platform Dashboard",
      "uid": "platform-${SERVICE_NAME}",
      "tags": ["platform", "${SERVICE_NAME}"],
      "timezone": "browser",
      "refresh": "15s",
      "schemaVersion": 36,
      "templating": {
        "list": [
          {
            "name": "namespace",
            "type": "constant",
            "current": {"value": "${APPS_NAMESPACE}"},
            "hide": 2
          }
        ]
      },
      "panels": [
        {
          "id": 1, "type": "stat", "title": "Running Pods",
          "gridPos": {"h": 4, "w": 6, "x": 0, "y": 0},
          "targets": [{
            "expr": "count(kube_pod_info{namespace=\"${APPS_NAMESPACE}\", pod=~\"${SERVICE_NAME}-.*\"})",
            "legendFormat": "pods"
          }],
          "options": {"colorMode": "background", "graphMode": "none"}
        },
        {
          "id": 2, "type": "stat", "title": "Request Rate (5m)",
          "gridPos": {"h": 4, "w": 6, "x": 6, "y": 0},
          "targets": [{
            "expr": "sum(rate(http_requests_total{service=\"${SERVICE_NAME}\",namespace=\"${APPS_NAMESPACE}\"}[5m]))",
            "legendFormat": "req/s"
          }],
          "options": {"colorMode": "background", "graphMode": "area"}
        },
        {
          "id": 3, "type": "stat", "title": "Error Rate (5m)",
          "gridPos": {"h": 4, "w": 6, "x": 12, "y": 0},
          "targets": [{
            "expr": "sum(rate(http_requests_total{service=\"${SERVICE_NAME}\",namespace=\"${APPS_NAMESPACE}\",status=~\"5..\"}[5m]))",
            "legendFormat": "err/s"
          }],
          "fieldConfig": {
            "defaults": {"thresholds": {"steps": [{"color": "green","value": 0},{"color": "red","value": 0.01}]}}
          },
          "options": {"colorMode": "background", "graphMode": "none"}
        },
        {
          "id": 4, "type": "stat", "title": "P95 Latency",
          "gridPos": {"h": 4, "w": 6, "x": 18, "y": 0},
          "targets": [{
            "expr": "histogram_quantile(0.95, sum(rate(http_request_duration_seconds_bucket{service=\"${SERVICE_NAME}\",namespace=\"${APPS_NAMESPACE}\"}[5m])) by (le))",
            "legendFormat": "p95"
          }],
          "fieldConfig": {"defaults": {"unit": "s"}},
          "options": {"colorMode": "background"}
        },
        {
          "id": 5, "type": "timeseries", "title": "Request Rate",
          "gridPos": {"h": 8, "w": 12, "x": 0, "y": 4},
          "targets": [
            {
              "expr": "sum(rate(http_requests_total{service=\"${SERVICE_NAME}\",namespace=\"${APPS_NAMESPACE}\"}[5m])) by (status)",
              "legendFormat": "{{status}}"
            }
          ],
          "fieldConfig": {"defaults": {"unit": "reqps"}}
        },
        {
          "id": 6, "type": "timeseries", "title": "Memory Usage",
          "gridPos": {"h": 8, "w": 12, "x": 12, "y": 4},
          "targets": [{
            "expr": "sum(container_memory_working_set_bytes{namespace=\"${APPS_NAMESPACE}\",pod=~\"${SERVICE_NAME}-.*\",container!=\"\"}) by (pod)",
            "legendFormat": "{{pod}}"
          }],
          "fieldConfig": {"defaults": {"unit": "bytes"}}
        },
        {
          "id": 7, "type": "timeseries", "title": "CPU Usage",
          "gridPos": {"h": 8, "w": 12, "x": 0, "y": 12},
          "targets": [{
            "expr": "sum(rate(container_cpu_usage_seconds_total{namespace=\"${APPS_NAMESPACE}\",pod=~\"${SERVICE_NAME}-.*\",container!=\"\"}[5m])) by (pod)",
            "legendFormat": "{{pod}}"
          }],
          "fieldConfig": {"defaults": {"unit": "short", "custom": {"lineWidth": 2}}}
        },
        {
          "id": 8, "type": "timeseries", "title": "Replica Count",
          "gridPos": {"h": 8, "w": 12, "x": 12, "y": 12},
          "targets": [{
            "expr": "kube_deployment_status_replicas_ready{namespace=\"${APPS_NAMESPACE}\",deployment=\"${SERVICE_NAME}\"}",
            "legendFormat": "ready"
          },{
            "expr": "kube_deployment_spec_replicas{namespace=\"${APPS_NAMESPACE}\",deployment=\"${SERVICE_NAME}\"}",
            "legendFormat": "desired"
          }]
        }
      ]
    }
YAML

  info "Generated: $out_dir/09-grafana-dashboard.yaml"
  echo "$out_dir/09-grafana-dashboard.yaml"
}

apply_manifests() {
  local sm="$1" dash="$2"
  if [[ "$APPLY" == "true" ]]; then
    kubectl apply -f "$sm"
    kubectl apply -f "$dash"
    success "ServiceMonitor and dashboard applied for $SERVICE_NAME"
  else
    info "Skipping apply (--no-apply). Apply manually:"
    echo "  kubectl apply -f $sm"
    echo "  kubectl apply -f $dash"
  fi
}

print_summary() {
  header "Monitoring configured — $SERVICE_NAME"
  echo ""
  echo "  Scraping : ${METRICS_PATH} every ${SCRAPE_INTERVAL}"
  echo "  Port     : ${METRICS_PORT}"
  echo ""
  echo "  Verify scraping:"
  echo "    kubectl get servicemonitor $SERVICE_NAME -n $APPS_NAMESPACE"
  echo ""
  echo "  Prometheus targets: http://localhost:9090/targets (after port-forward)"
  echo "  Grafana dashboard : http://localhost:3000 → Dashboards → ${SERVICE_NAME}"
}

main() {
  parse_args "$@"
  header "Kubernetes Platform — Monitoring Setup"
  load_config
  local sm dash
  sm=$(gen_servicemonitor)
  dash=$(gen_service_dashboard)
  apply_manifests "$sm" "$dash"
  print_summary
}

main "$@"
