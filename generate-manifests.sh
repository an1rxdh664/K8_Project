#!/usr/bin/env bash
# generate-manifests.sh
# Generates all Kubernetes manifests for an onboarded service from its .onboard.conf.
# Produces: Deployment, Service, ConfigMap, ServiceAccount, Role, RoleBinding.
# Kubernetes Secret is NOT generated as YAML — it was created by onboard.sh directly
# so values are never on disk. Re-run onboard.sh to recreate or use rotate-secret.sh.
#
# Usage:
#   ./generate-manifests.sh <path/to/service.onboard.conf>
#   ./generate-manifests.sh --help

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'
CYAN='\033[0;36m'; BOLD='\033[1m'; NC='\033[0m'
info()    { echo -e "${CYAN}[INFO]${NC}  $*"; }
success() { echo -e "${GREEN}[OK]${NC}    $*"; }
warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
die()     { echo -e "${RED}[ERROR]${NC} $*" >&2; exit 1; }
header()  { echo -e "\n${BOLD}${CYAN}$*${NC}"; }

CONF_FILE=""
PLATFORM_NAMESPACE="${PLATFORM_NAMESPACE:-platform}"
DRY_RUN="${DRY_RUN:-false}"   # DRY_RUN=true prints YAML without applying

usage() {
  cat <<EOF
${BOLD}generate-manifests.sh${NC} — Generate Kubernetes manifests from onboarding config

${BOLD}Usage:${NC}
  ./generate-manifests.sh <service.onboard.conf>
  DRY_RUN=true ./generate-manifests.sh <service.onboard.conf>   # print YAML only

${BOLD}Output:${NC}
  manifests/<service-name>/
    00-namespace.yaml        (reference only — namespace already exists)
    01-serviceaccount.yaml
    02-rbac.yaml
    03-configmap.yaml
    04-deployment.yaml
    05-service.yaml
    kustomization.yaml       (apply order guaranteed)

${BOLD}Notes:${NC}
  - Kubernetes Secret is NOT generated as YAML (values never on disk).
    Secret was created by onboard.sh. To recreate: re-run onboard.sh.
    To rotate a key: ./rotate-secret.sh --service <name> --key <KEY>
EOF
  exit 0
}

# ── Load config ───────────────────────────────────────────────────────────────
load_config() {
  [[ -f "$CONF_FILE" ]] || die "Config file not found: $CONF_FILE"
  # shellcheck source=/dev/null
  source "$CONF_FILE"

  for var in SERVICE_NAME PORT REPLICAS REGISTRY_ADDRESS APPS_NAMESPACE \
             CPU_REQUEST CPU_LIMIT MEM_REQUEST MEM_LIMIT \
             LIVENESS_PATH READINESS_PATH HEALTH_INITIAL_DELAY; do
    [[ -n "${!var:-}" ]] || die "Config missing: $var (in $CONF_FILE)"
  done

  # Load build result for image ref if available
  local result_file
  result_file="$(dirname "$CONF_FILE")/${SERVICE_NAME}.build.result"
  if [[ -f "$result_file" ]]; then
    # shellcheck source=/dev/null
    source "$result_file"
    info "Using image from build result: $IMAGE_REF"
  else
    # Fallback: construct image ref from registry + service name + latest
    IMAGE_REF="${REGISTRY_ADDRESS}/${SERVICE_NAME}:latest"
    warn "No build result found — using $IMAGE_REF (run build.sh first for a versioned tag)"
  fi
}

# ── Output directory ──────────────────────────────────────────────────────────
init_output_dir() {
  OUT_DIR="$(dirname "$CONF_FILE")/${SERVICE_NAME}"
  mkdir -p "$OUT_DIR"
  info "Output directory: $OUT_DIR"
}

# ── Helpers for YAML generation ───────────────────────────────────────────────

# Render non-secret env vars as YAML env entries
render_env_vars() {
  local indent="${1:-16}"
  local pad
  pad=$(printf '%*s' "$indent" '')

  if [[ ${#ENV_VARS[@]:-0} -eq 0 ]]; then
    return
  fi

  for ev in "${ENV_VARS[@]}"; do
    local key="${ev%%=*}"
    local val="${ev#*=}"
    echo "${pad}- name: ${key}"
    echo "${pad}  value: $(printf '%q' "${val}" | sed "s/\\\\'/'/")"
  done
}

# Render secret refs as env entries
render_secret_env() {
  local indent="${1:-16}"
  local pad
  pad=$(printf '%*s' "$indent" '')

  if [[ ${#SECRET_NAMES[@]:-0} -eq 0 ]]; then
    return
  fi

  for sn in "${SECRET_NAMES[@]}"; do
    echo "${pad}- name: ${sn}"
    echo "${pad}  valueFrom:"
    echo "${pad}    secretKeyRef:"
    echo "${pad}      name: ${SERVICE_NAME}-secrets"
    echo "${pad}      key: ${sn}"
  done
}

# ── 01 — ServiceAccount ───────────────────────────────────────────────────────
gen_serviceaccount() {
  cat > "$OUT_DIR/01-serviceaccount.yaml" <<EOF
# 01-serviceaccount.yaml — ServiceAccount for $SERVICE_NAME
# Generated by generate-manifests.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: v1
kind: ServiceAccount
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    app.kubernetes.io/managed-by: platform
automountServiceAccountToken: false
EOF
  info "Generated: 01-serviceaccount.yaml"
}

# ── 02 — RBAC (per-service, least privilege) ──────────────────────────────────
gen_rbac() {
  # Services get no cluster permissions by default.
  # If DB_MODE=isolated, they get access to their own ConfigMap only.
  # Extend here as needed per-service — but nothing is hardcoded.
  local rules=""

  if [[ "${DB_MODE:-none}" == "isolated" ]]; then
    rules='
  - apiGroups: [""]
    resources: ["configmaps"]
    resourceNames: ["'"${SERVICE_NAME}"'-db-config"]
    verbs: ["get"]'
  fi

  cat > "$OUT_DIR/02-rbac.yaml" <<EOF
# 02-rbac.yaml — RBAC for $SERVICE_NAME
# Generated by generate-manifests.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: rbac.authorization.k8s.io/v1
kind: Role
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
rules:${rules:-
  [] # No permissions needed by default}
---
apiVersion: rbac.authorization.k8s.io/v1
kind: RoleBinding
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
subjects:
  - kind: ServiceAccount
    name: ${SERVICE_NAME}
    namespace: ${APPS_NAMESPACE}
roleRef:
  kind: Role
  name: ${SERVICE_NAME}
  apiGroup: rbac.authorization.k8s.io
EOF
  info "Generated: 02-rbac.yaml"
}

# ── 03 — ConfigMap ────────────────────────────────────────────────────────────
gen_configmap() {
  # ConfigMap holds non-secret env configuration.
  # Also stores DB mode and port for platform tooling (dashboard, Phase 3).
  local data_entries=""
  if [[ ${#ENV_VARS[@]:-0} -gt 0 ]]; then
    for ev in "${ENV_VARS[@]}"; do
      local key="${ev%%=*}"
      local val="${ev#*=}"
      data_entries+="  ${key}: \"${val}\"\n"
    done
  fi

  cat > "$OUT_DIR/03-configmap.yaml" <<EOF
# 03-configmap.yaml — Non-secret config for $SERVICE_NAME
# Generated by generate-manifests.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: v1
kind: ConfigMap
metadata:
  name: ${SERVICE_NAME}-config
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    app.kubernetes.io/managed-by: platform
  annotations:
    platform/repo-url: "${REPO_URL}"
    platform/branch: "${BRANCH}"
    platform/build-method: "${BUILD_METHOD}"
    platform/db-mode: "${DB_MODE}"
    platform/port: "${PORT}"
data:
  PORT: "${PORT}"
  DB_MODE: "${DB_MODE}"
$(printf '%b' "$data_entries")EOF
  info "Generated: 03-configmap.yaml"
}

# ── 04 — Deployment ───────────────────────────────────────────────────────────
gen_deployment() {
  # Build env section combining configmap ref, non-secret vars, and secret refs
  local env_section=""

  # Always inject PORT from ConfigMap
  env_section+="            - name: PORT
              valueFrom:
                configMapKeyRef:
                  name: ${SERVICE_NAME}-config
                  key: PORT
"

  # Non-secret vars
  if [[ ${#ENV_VARS[@]:-0} -gt 0 ]]; then
    for ev in "${ENV_VARS[@]}"; do
      local key="${ev%%=*}"
      local val="${ev#*=}"
      env_section+="            - name: ${key}
              value: \"${val}\"
"
    done
  fi

  # Secret refs
  if [[ ${#SECRET_NAMES[@]:-0} -gt 0 ]]; then
    for sn in "${SECRET_NAMES[@]}"; do
      env_section+="            - name: ${sn}
              valueFrom:
                secretKeyRef:
                  name: ${SERVICE_NAME}-secrets
                  key: ${sn}
"
    done
  fi

  cat > "$OUT_DIR/04-deployment.yaml" <<EOF
# 04-deployment.yaml — Deployment for $SERVICE_NAME
# Generated by generate-manifests.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    app.kubernetes.io/managed-by: platform
  annotations:
    platform/repo-url: "${REPO_URL}"
    platform/branch: "${BRANCH}"
    platform/image: "${IMAGE_REF}"
spec:
  replicas: ${REPLICAS}
  selector:
    matchLabels:
      app.kubernetes.io/name: ${SERVICE_NAME}
  strategy:
    type: RollingUpdate
    rollingUpdate:
      maxUnavailable: 0
      maxSurge: 1
  template:
    metadata:
      labels:
        app.kubernetes.io/name: ${SERVICE_NAME}
        app.kubernetes.io/part-of: k8s-platform
      annotations:
        # Force pod restart when config changes
        checksum/config: "{{ config-hash-placeholder }}"
    spec:
      serviceAccountName: ${SERVICE_NAME}
      automountServiceAccountToken: false
      securityContext:
        runAsNonRoot: true
        seccompProfile:
          type: RuntimeDefault
      containers:
        - name: ${SERVICE_NAME}
          image: ${IMAGE_REF}
          imagePullPolicy: Always
          securityContext:
            allowPrivilegeEscalation: false
            readOnlyRootFilesystem: true
            capabilities:
              drop: ["ALL"]
          ports:
            - name: http
              containerPort: ${PORT}
              protocol: TCP
          env:
${env_section}
          resources:
            requests:
              cpu: ${CPU_REQUEST}
              memory: ${MEM_REQUEST}
            limits:
              cpu: ${CPU_LIMIT}
              memory: ${MEM_LIMIT}
          livenessProbe:
            httpGet:
              path: ${LIVENESS_PATH}
              port: http
            initialDelaySeconds: ${HEALTH_INITIAL_DELAY}
            periodSeconds: 15
            timeoutSeconds: 5
            failureThreshold: 3
          readinessProbe:
            httpGet:
              path: ${READINESS_PATH}
              port: http
            initialDelaySeconds: 5
            periodSeconds: 10
            timeoutSeconds: 3
            failureThreshold: 2
          # tmpfs for read-only root filesystem
          volumeMounts:
            - name: tmp
              mountPath: /tmp
      volumes:
        - name: tmp
          emptyDir: {}
      terminationGracePeriodSeconds: 30
EOF
  info "Generated: 04-deployment.yaml"
}

# ── 05 — Service ──────────────────────────────────────────────────────────────
gen_service() {
  cat > "$OUT_DIR/05-service.yaml" <<EOF
# 05-service.yaml — Service for $SERVICE_NAME
# Generated by generate-manifests.sh — $(date -u +"%Y-%m-%dT%H:%M:%SZ")
apiVersion: v1
kind: Service
metadata:
  name: ${SERVICE_NAME}
  namespace: ${APPS_NAMESPACE}
  labels:
    app.kubernetes.io/name: ${SERVICE_NAME}
    app.kubernetes.io/part-of: k8s-platform
    app.kubernetes.io/managed-by: platform
spec:
  selector:
    app.kubernetes.io/name: ${SERVICE_NAME}
  ports:
    - name: http
      protocol: TCP
      port: 80
      targetPort: http
  type: ClusterIP
EOF
  info "Generated: 05-service.yaml"
}

# ── kustomization.yaml (apply order) ─────────────────────────────────────────
gen_kustomization() {
  cat > "$OUT_DIR/kustomization.yaml" <<EOF
# kustomization.yaml — apply order for $SERVICE_NAME
# kubectl apply -k manifests/${SERVICE_NAME}/
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
namespace: ${APPS_NAMESPACE}
resources:
  - 01-serviceaccount.yaml
  - 02-rbac.yaml
  - 03-configmap.yaml
  - 04-deployment.yaml
  - 05-service.yaml
EOF
  info "Generated: kustomization.yaml"
}

# ── Optional: dry run print ────────────────────────────────────────────────────
print_dry_run() {
  header "DRY RUN — Generated YAML"
  for f in \
    "$OUT_DIR/01-serviceaccount.yaml" \
    "$OUT_DIR/02-rbac.yaml" \
    "$OUT_DIR/03-configmap.yaml" \
    "$OUT_DIR/04-deployment.yaml" \
    "$OUT_DIR/05-service.yaml"; do
    echo ""
    echo "──────────────── $(basename "$f") ────────────────"
    cat "$f"
  done
}

# ── Summary ───────────────────────────────────────────────────────────────────
print_summary() {
  header "Manifests generated — $SERVICE_NAME"
  echo ""
  echo "  Output : $OUT_DIR/"
  echo "  Image  : $IMAGE_REF"
  echo "  NS     : $APPS_NAMESPACE"
  echo ""
  echo "  Apply:"
  echo "    kubectl apply -k $OUT_DIR/"
  echo ""
  echo "  Or file by file:"
  echo "    kubectl apply -f $OUT_DIR/01-serviceaccount.yaml"
  echo "    kubectl apply -f $OUT_DIR/02-rbac.yaml"
  echo "    kubectl apply -f $OUT_DIR/03-configmap.yaml"
  echo "    kubectl apply -f $OUT_DIR/04-deployment.yaml"
  echo "    kubectl apply -f $OUT_DIR/05-service.yaml"
  echo ""
  if [[ ${#SECRET_NAMES[@]:-0} -gt 0 ]]; then
    echo "  ${YELLOW}Note:${NC} Secret '${SERVICE_NAME}-secrets' was created by onboard.sh."
    echo "  It is not regenerated here. To recreate: re-run onboard.sh"
    echo "  To rotate a key: ./rotate-secret.sh --service $SERVICE_NAME --key <KEY>"
    echo ""
  fi
}

# ── Main ──────────────────────────────────────────────────────────────────────
main() {
  case "${1:-}" in
    --help|-h) usage ;;
    "") die "Usage: ./generate-manifests.sh <service.onboard.conf>  |  --help" ;;
    *) CONF_FILE="$1" ;;
  esac

  header "Kubernetes Platform — Manifest Generator"

  load_config
  init_output_dir
  gen_serviceaccount
  gen_rbac
  gen_configmap
  gen_deployment
  gen_service
  gen_kustomization

  if [[ "$DRY_RUN" == "true" ]]; then
    print_dry_run
  fi

  print_summary
}

main "$@"
